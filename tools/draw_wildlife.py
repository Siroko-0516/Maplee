"""Bake GMS v83 monster framebooks from the public maplestory.io renderer.

The deployed game uses only the packed PNG and Python tables. For regeneration,
--cache PATH reuses the animation metadata, lossless PNGs and WZ origin metadata.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
import json
from pathlib import Path
from pprint import pformat
from tempfile import TemporaryDirectory
from time import sleep
from urllib.request import Request, urlopen

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
# Maplee species order, source WZ ID and fitted longest idle side before elite scale.
SOURCES = (
    (210100, 52), (1210102, 63), (130101, 47), (1210101, 64),
    (5220000, 74), (3230102, 68), (1210103, 55), (5130101, 80),
    (3230200, 63), (4230104, 68), (6130101, 77),
)
API = "https://maplestory.io/api/"


def read(cache, path):
    file = cache / path.replace("/", "-")
    if file.exists():
        return file.read_bytes()
    request = Request(API + path, headers={"User-Agent": "Maplee sprite builder"})
    for attempt in range(3):
        try:
            with urlopen(request, timeout=30) as response:
                data = response.read()
            file.write_bytes(data)
            return data
        except OSError:
            if attempt == 2:
                raise
            sleep(1 + attempt)


def framebook(cache, source, action, count):
    route = f"GMS/83/mob/{source}/render/{action}"
    gif = Image.open(BytesIO(read(cache, route)))
    delays = []
    for i in range(gif.n_frames):
        gif.seek(i)
        delays.append(max(1, round(gif.info.get("duration", 100)*60/1000)))

    indices = list(range(count))
    if len(delays) == 2*count-2 and len(delays) > count:
        indices.extend(range(count-2, 0, -1))
    if len(indices) != len(delays):
        raise ValueError(f"Unexpected GIF sequence for {source}/{action}")

    def cel(i):
        # Use the PNG rather than the GIF's reduced palette. Each WZ origin
        # registers the body, airborne feet and spell effects to one anchor.
        image = Image.open(BytesIO(read(cache, f"{route}/{i}"))).convert("RGBA")
        origin_path = f"wz/GMS/83/Mob/{source:07}.img/{action}/{i}/origin"
        origin = json.loads(read(cache, origin_path))["value"]
        box = image.getchannel("A").getbbox()
        if not box:
            return Image.new("RGBA", (1,1)), 0, 0
        art = image.crop(box).transpose(Image.Transpose.FLIP_LEFT_RIGHT)
        return art, origin["x"]-box[2], box[1]-origin["y"]

    pictures = [cel(i) for i in range(count)]
    return [(*pictures[i], ticks) for i, ticks in zip(indices,delays)]


def bake(cache):
    frames, rows, cells = [], [], []
    for code, longest in SOURCES:
        meta = json.loads(read(cache, f"GMS/83/mob/{code}"))
        available = meta["framebooks"]
        actions = [action for action in ("stand", "move", "jump", "hit1", "die1", "attack1", "skill1")
                   if action in available and (action != "skill1" or "attack1" not in available)]
        with ThreadPoolExecutor(max_workers=4) as pool:
            books = dict(zip(actions, pool.map(lambda action: framebook(cache,code,action,available[action]), actions)))
        idle, left, top, _ = books["stand"][0]
        scale = min(1.0, longest/max(idle.size))
        size = tuple(max(1,round(side*scale)) for side in idle.size)
        baseline = top + idle.height
        center = left + idle.width/2
        ranges = {}
        for action, cels in books.items():
            start = len(frames)
            elapsed = 0
            ends = []
            for image, dx, dy, ticks in cels:
                fitted = tuple(max(1,round(side*scale)) for side in image.size)
                frames.append(image.resize(fitted, Image.Resampling.NEAREST))
                cells.append((round((dx-center)*scale), round((dy-baseline)*scale)))
                elapsed += ticks
                ends.append(elapsed)
            ranges[action] = (start, tuple(ends))
        rows.append((code, size, ranges))
        print(meta["name"].strip(), size, len(frames))
    # Pack tight rectangles, ordered by height, without wasting a full boss
    # attack's worth of space on every small snail or mushroom frame.
    atlas_width = 1024
    rects = [None] * len(frames)
    x = y = shelf = 0
    for i in sorted(range(len(frames)), key=lambda i: -frames[i].height):
        w, h = frames[i].size
        if x+w > atlas_width:
            y += shelf + 1
            x = shelf = 0
        rects[i] = (x, y, w, h, *cells[i])
        x += w+1
        shelf = max(shelf, h)
    atlas = Image.new("RGBA",(atlas_width, y+shelf))
    for image, rect in zip(frames,rects):
        atlas.paste(image,rect[:2])
    atlas.save(ROOT / "assets/wildlife.png", optimize=True)
    data = ('"""GMS v83 monster art. Generated by tools/draw_wildlife.py."""\n'
            '# Each book lists its first atlas index and cumulative durations in simulation ticks.\n'
            'MOB_BOOKS = '+pformat(tuple(rows),width=110,sort_dicts=False)+'\n\n'
            '# Packed rectangle x, y, width, height and offset from the field ground anchor.\n'
            'MOB_FRAMES = '+pformat(tuple(rects),width=110)+'\n')
    (ROOT / "maplee/wildlife_data.py").write_text(data)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path)
    args = parser.parse_args()
    if args.cache:
        args.cache.mkdir(exist_ok=True, parents=True)
        bake(args.cache)
    else:
        with TemporaryDirectory() as temporary:
            bake(Path(temporary))
