"""Bake registered MapleStory GMS v83 WZ skill effects from maplestory.io."""
import base64
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
import json
from pathlib import Path
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
BASE = "https://maplestory.io/api/wz/GMS/83/Skill/"
# Row order matches COMBAT_ART. Maximum scales preserve native detail.
SKILLS = (
    ("slash", "100.img/skill/1001004/effect", .65),  # Power Strike
    ("arc", "100.img/skill/1001005/effect", .85),  # Slash Blast
    ("impact", "100.img/skill/1001004/hit/0", .60),
    ("arrow", "310.img/skill/3101005/ball", .78),    # Arrow Bomb
    ("bolt", "200.img/skill/2001004/ball", .85),    # Energy Bolt
    ("ring", "230.img/skill/2301002/effect", .9),   # Heal
    ("stars", "220.img/skill/2201005/effect", 1),    # Thunder Bolt
    ("arc_hit", "100.img/skill/1001005/hit/0", .82),
    ("bolt_hit", "200.img/skill/2001004/hit/0", .82),
    ("stars_hit", "220.img/skill/2201005/hit/0", .91),
    ("ring_hit", "230.img/skill/2301002/hit/0", .88),
    ("arrow_hit", "310.img/skill/3101005/hit/0", .78),
    ("buff_guardian", "110.img/skill/1101007/effect", .78),  # Power Guard
    ("buff_ranger", "410.img/skill/4101004/effect", .85),    # Haste
    ("buff_mage", "200.img/skill/2001002/effect", .85),      # Magic Guard
)
WIDTH, HEIGHT = 320, 224
ANCHOR = (160, 168)


def node(path):
    raw = subprocess.check_output(["curl", "--fail", "--silent", "--show-error",
                                   "--retry", "3", "--max-time", "45", BASE + path])
    return json.loads(raw)


def read_frame(path):
    frame = node(path)
    image = Image.open(BytesIO(base64.b64decode(frame["value"]))).convert("RGBA")
    origin = node(path + "/origin")["value"]
    return image.transpose(Image.Transpose.FLIP_LEFT_RIGHT), image.width-origin["x"], origin["y"]


def build():
    rows = []
    with ThreadPoolExecutor(max_workers=8) as pool:
        for name, path, scale in SKILLS:
            names = sorted((n for n in node(path)["children"] if n.isdecimal()), key=int)
            frames = list(pool.map(read_frame, [path + "/" + n for n in names]))
            # Register to the original action origin across every cel before resizing.
            for image, x, y in frames:
                for extent, room in ((x, ANCHOR[0]), (image.width-x, WIDTH-ANCHOR[0]),
                                     (y, ANCHOR[1]), (image.height-y, HEIGHT-ANCHOR[1])):
                    if extent > 0:
                        scale = min(scale, (room-1)/extent)
            cells = []
            for image, x, y in frames:
                cel = Image.new("RGBA", (WIDTH, HEIGHT))
                size = (max(1, round(image.width*scale)), max(1, round(image.height*scale)))
                cel.paste(image.resize(size, Image.Resampling.NEAREST),
                          (ANCHOR[0]-round(x*scale), ANCHOR[1]-round(y*scale)))
                cells.append(cel)
            bounds = [cell.getbbox() for cell in cells]
            x0, y0 = min(b[0] for b in bounds), min(b[1] for b in bounds)
            box = (x0, y0, max(b[2] for b in bounds), max(b[3] for b in bounds))
            rows.append((name, [cell.crop(box) for cell in cells], ANCHOR[0]-x0, ANCHOR[1]-y0))
    width = max(len(cells)*cells[0].width for _,cells,_,_ in rows)
    height = sum(cells[0].height for _,cells,_,_ in rows)
    sheet = Image.new("RGBA", (width,height))
    metadata = ['"""Generated by tools/draw_combat.py. Row y, width, height, origin x/y, count."""',
                "COMBAT_ART = {"]
    top = 0
    for name,cells,origin_x,origin_y in rows:
        w,h = cells[0].size
        for col,cell in enumerate(cells):
            sheet.paste(cell,(col*w,top))
        metadata.append(f'    "{name}": {(top,w,h,origin_x,origin_y,len(cells))},')
        top += h
    sheet.save(ASSETS/"combat-fx.png", optimize=True)
    (ROOT/"maplee/combat_art.py").write_text("\n".join(metadata + ["}", ""]))
    print("Combat atlas", sheet.size, "frames", sum(len(r[1]) for r in rows))


if __name__ == "__main__":
    build()
