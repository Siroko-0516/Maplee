"""Pack the licensed forest layers and monster cels from local source downloads."""

from argparse import ArgumentParser
from io import BytesIO
from itertools import accumulate
from pathlib import Path
from pprint import pformat
from zipfile import ZipFile

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
FOREST_LAYER = "Tall Forest Files/Layers/middle.png"


def png(archive, path):
    return Image.open(BytesIO(archive.read(path))).convert("RGBA")


def split(image, width, height):
    """Read frames left to right, omitting empty cells at the end of a sheet."""
    for y in range(0, image.height, height):
        for x in range(0, image.width, width):
            frame = image.crop((x, y, x + width, y + height))
            if frame.getchannel("A").getbbox():
                yield frame


def tint(image, hue_shift):
    if not hue_shift:
        return image
    hue, saturation, value = image.convert("HSV").split()
    hue = hue.point([(i + hue_shift) % 256 for i in range(256)])
    shifted = Image.merge("HSV", (hue, saturation, value)).convert("RGBA")
    shifted.putalpha(image.getchannel("A"))
    return shifted


class Atlas:
    def __init__(self):
        self.frames = []
        self.books = {}

    def add(self, source, actions, center, ground, scale, hue=0, flip=False):
        books = {}
        for name, (frames, duration) in actions.items():
            first = len(self.frames)
            for frame in frames:
                if flip:
                    frame = frame.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
                frame = tint(frame, hue)
                box = frame.getchannel("A").getbbox()
                if not box:
                    continue
                left, top, right, bottom = (round(value * scale) for value in box)
                cel = frame.crop(box).resize((max(1, right - left), max(1, bottom - top)),
                                             Image.Resampling.NEAREST)
                self.frames.append((cel, left - round(center * scale), top - round(ground * scale)))
            books[name] = (first, tuple(accumulate([duration] * (len(self.frames) - first))))
        self.books[source] = books

    def save(self):
        width = 1024
        x = y = shelf = 0
        rects = [None] * len(self.frames)
        for i in sorted(range(len(self.frames)), key=lambda index: -self.frames[index][0].height):
            cel, dx, dy = self.frames[i]
            w, h = cel.size
            if x + w > width:
                x, y, shelf = 0, y + shelf + 1, 0
            rects[i] = (x, y, w, h, dx, dy)
            x += w + 1
            shelf = max(shelf, h)
        atlas = Image.new("RGBA", (width, y + shelf))
        for (cel, _, _), rect in zip(self.frames, rects):
            atlas.paste(cel, rect[:2])
        atlas.save(ASSETS / "open-wildlife.png", optimize=True)
        data = (
            '"""Licensed monster animation data generated by tools/pack_open_art.py."""\n\n'
            "OPEN_MOB_BOOKS = " + pformat(self.books, width=105, sort_dicts=False)
            + "\n\nOPEN_MOB_FRAMES = " + pformat(tuple(rects), width=105) + "\n"
        )
        (ROOT / "maplee/open_wildlife.py").write_text(data, encoding="utf-8")


def pack_monsters(args):
    atlas = Atlas()
    with ZipFile(args.slime) as archive:
        frames = [png(archive, f"Individual Sprites/slime{i}.png") for i in range(1, 18)]
    atlas.add(210100, {
        "stand": (frames[:4], 12), "move": (frames[4:10], 6),
        "attack1": (frames[10:14], 7), "hit1": (frames[14:], 4),
        "die1": (frames[14:] + [frames[8]], 5),
    }, center=16, ground=24, scale=2, hue=-64, flip=True)

    with Image.open(args.snail) as crawl, Image.open(args.snail_fall) as fall:
        move = list(split(crawl.convert("RGBA"), 83, 53))
        death = list(split(fall.convert("RGBA"), 81, 52))
    atlas.add(130101, {
        "stand": (move[:1], 24), "move": (move + move[1:2], 8),
        "hit1": (death[:2], 5), "die1": (death, 6),
    }, center=41, ground=53, scale=0.54, hue=77)

    with ZipFile(args.mushroom) as archive:
        mushrooms = {}
        for folder, (action, duration) in enumerate(
            (("stand", 6), ("move", 4), ("attack1", 5), ("hit1", 3), ("die1", 5)), 1
        ):
            members = sorted(p for p in archive.namelist()
                             if p.startswith(f"Mushroom/{folder:02}_") and p.endswith(".png"))
            mushrooms[action] = ([png(archive, p) for p in members], duration)
    atlas.add(1210102, mushrooms, center=118, ground=260, scale=0.29)
    atlas.add(6130101, mushrooms, center=118, ground=260, scale=0.37, hue=-56)

    with ZipFile(args.galore) as archive:
        def actions(prefix, names):
            return {
                action: (list(split(png(archive, f"{prefix}_{name}.png"), 64, 64)), duration)
                for action, (name, duration) in zip(
                    ("stand", "move", "attack1", "hit1", "die1"), names
                )
            }

        crabs = actions("Crab/Crab", (("Idle", 10), ("Run", 5), ("AttackA", 4),
                                       ("Hit", 4), ("Death", 6)))
        atlas.add(5220000, crabs, center=30, ground=48, scale=3, hue=11)
        atlas.add(3230102, crabs, center=30, ground=48, scale=3)
        atlas.add(4230104, crabs, center=30, ground=48, scale=3, hue=139)
        spiked = actions("Slime/Slime_Spiked", (("Idle", 10), ("Run", 6), ("Ability", 7),
                                               ("Hit", 4), ("Death", 6)))
        atlas.add(1210103, spiked, center=30, ground=48, scale=3, hue=33)
        golem = actions("Golem/No Armor/Golem", (("IdleA", 12), ("Run", 8), ("AttackA", 4),
                                               ("HitA", 3), ("DeathA", 7)))
        atlas.add(5130101, golem, center=32, ground=47, scale=3)
    atlas.save()


def pack_forest(path):
    with ZipFile(path) as archive:
        tree = png(archive, FOREST_LAYER)
    backdrop = Image.open(ASSETS / "daylight-panorama-tall.png").convert("RGBA")
    tree = tree.resize((tree.width * 2, tree.height * 2), Image.Resampling.NEAREST)
    alpha = tree.getchannel("A")
    # Blend the source layer's cropped edges into the sky and distant foliage.
    for y in range(tree.height):
        opacity = min(1, y / 66, (tree.height - 1 - y) / 44)
        row = alpha.crop((0, y, tree.width, y + 1)).point(
            [round(v * opacity * 0.9) for v in range(256)]
        )
        alpha.paste(row, (0, y))
    tree.putalpha(alpha)
    flipped = tree.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
    for x, y, layer in ((34, 150, tree), (406, 112, flipped), (770, 153, tree),
                        (1150, 123, flipped), (1560, 147, flipped), (1950, 122, tree)):
        backdrop.alpha_composite(layer, (x, y))
    backdrop.convert("RGB").save(ASSETS / "bellflower-forest.png", optimize=True)


if __name__ == "__main__":
    parser = ArgumentParser(description=__doc__)
    for name in ("forest", "slime", "snail", "snail-fall", "mushroom", "galore"):
        parser.add_argument(f"--{name}", type=Path, required=True)
    sources = parser.parse_args()
    pack_monsters(sources)
    pack_forest(sources.forest)
